#!/usr/bin/env node
/**
 * Refresh `apps/api/src/workflows/__fixtures__/object-info.json` from a live
 * ComfyUI.
 *
 *   node tools/capture-object-info.mjs http://192.168.1.10:8188
 *
 * The fixture is what lets `validate-graph.ts` check every shipped graph
 * offline. It is partial on purpose — only the classes our templates actually
 * use — and this script keeps it that way: it reads the node classes out of the
 * graphs in `workflows/graphs/` and fetches exactly those. Capturing all ~600
 * would make a large file mostly about nodes we never emit.
 *
 * Two things it is careful about, because both would produce a fixture that
 * lies:
 *
 *   - **File-list enums are recorded as `fileList: true` with no values.** The
 *     options for `ckpt_name` are whatever happens to be installed on the
 *     machine you ran this against, and freezing them would turn "this backend
 *     has no LTX model" into a permanent property of the repository.
 *   - **Enum completeness is recorded, not assumed.** Everything fetched here
 *     is complete, so it writes `enumComplete: true` — but the flag exists
 *     because the first fixture was typed by hand from a truncated console
 *     dump, and a later reader has to be able to tell the two apart.
 */

import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const BACKEND = process.argv[2];
if (!BACKEND) {
  console.error('usage: node tools/capture-object-info.mjs <comfyui-url>');
  process.exit(2);
}

const ROOT = path.resolve(import.meta.dirname, '..');
const GRAPHS = path.join(ROOT, 'apps/api/src/workflows/graphs');
const OUT = path.join(ROOT, 'apps/api/src/workflows/__fixtures__/object-info.json');

/** Enums whose options are a property of the machine, never of the graph. */
const FILE_LIST = /_name$|^image$|^lora_name$/;

async function classesInGraphs() {
  const files = (await readdir(GRAPHS)).filter((f) => f.endsWith('.api.json'));
  const classes = new Set();
  for (const file of files) {
    const graph = JSON.parse(await readFile(path.join(GRAPHS, file), 'utf8'));
    for (const node of Object.values(graph)) {
      if (node?.class_type) classes.add(node.class_type);
    }
  }
  return [...classes].sort();
}

function describeInput(name, spec) {
  const [type, options = {}] = spec;
  if (Array.isArray(type)) {
    if (FILE_LIST.test(name)) return { type: 'ENUM', fileList: true };
    return { type: 'ENUM', values: type, enumComplete: true };
  }
  const out = { type };
  if (typeof options.min === 'number') out.min = options.min;
  if (typeof options.max === 'number') out.max = options.max;
  return out;
}

function describeNode(entry) {
  const out = {};
  for (const section of ['required', 'optional']) {
    const inputs = entry.input?.[section];
    if (!inputs) continue;
    out[section] = Object.fromEntries(
      Object.entries(inputs).map(([name, spec]) => [name, describeInput(name, spec)]),
    );
  }
  return out;
}

const wanted = await classesInGraphs();
console.log(`capturing ${wanted.length} classes from ${BACKEND}`);

const stats = await (await fetch(`${BACKEND}/system_stats`)).json();
const nodes = {};
const missing = [];

for (const name of wanted) {
  const res = await fetch(`${BACKEND}/object_info/${encodeURIComponent(name)}`);
  if (!res.ok) {
    missing.push(name);
    continue;
  }
  const body = await res.json();
  const entry = body[name];
  if (!entry) {
    missing.push(name);
    continue;
  }
  nodes[name] = describeNode(entry);
}

if (missing.length) {
  // Not fatal: a class this backend lacks is exactly what a graph validated
  // against it should be allowed to notice later.
  console.warn(`not on this backend: ${missing.join(', ')}`);
}

const fixture = {
  _meta: {
    source: `${BACKEND}/object_info`,
    comfyVersion: stats?.system?.comfyui_version ?? 'unknown',
    capturedAt: new Date().toISOString().slice(0, 10),
    note: 'Generated by tools/capture-object-info.mjs. Only the classes our graphs use.',
    ...(missing.length ? { missingFromBackend: missing } : {}),
  },
  nodes,
};

await writeFile(OUT, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${Object.keys(nodes).length} classes to ${path.relative(ROOT, OUT)}`);
